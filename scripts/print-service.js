#!/usr/bin/env node
/**
 * R99 Local Print Service
 * Set PRINTER_NAME env var to target a specific printer, e.g.:
 *   PRINTER_NAME="My_Thermal" npm run print-service
 */

import http from "http";
import { execSync } from "child_process";
import fs from "fs";
``;
import path from "path";
import os from "os";

const PORT = 3001;
const PRINTER_NAME = process.env.PRINTER_NAME ?? null;

const CHROME_CANDIDATES = [
  "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
  "/Applications/Chromium.app/Contents/MacOS/Chromium",
  "/Applications/Google Chrome Canary.app/Contents/MacOS/Google Chrome Canary",
  "/usr/bin/google-chrome",
  "/usr/bin/chromium-browser",
];

function findChrome() {
  for (const p of CHROME_CANDIDATES) {
    try {
      fs.accessSync(p);
      return p;
    } catch {}
  }
  return null;
}

function listPrinters() {
  try {
    return execSync("lpstat -a 2>/dev/null")
      .toString()
      .trim()
      .split("\n")
      .map((l) => l.split(" ")[0])
      .filter(Boolean);
  } catch {
    return [];
  }
}

function resolvePrinter() {
  if (PRINTER_NAME) return PRINTER_NAME;

  // Try CUPS default
  try {
    const out = execSync("lpstat -d 2>/dev/null").toString();
    const m = out.match(/destination:\s*(\S+)/);
    if (m && m[1] !== "default") return m[1];
  } catch {}

  // Fall back to first available printer
  const printers = listPrinters();
  return printers[0] ?? null;
}

function printHtml(html) {
  const chrome = findChrome();
  if (!chrome) throw new Error("Chrome not found. Install Google Chrome.");

  const id = Date.now();
  const htmlFile = path.join(os.tmpdir(), `r99-print-${id}.html`);
  const pdfFile = path.join(os.tmpdir(), `r99-print-${id}.pdf`);

  fs.writeFileSync(htmlFile, html, "utf8");

  try {
    // HTML → PDF via Chrome headless (uses @page { size: 58mm 102mm } from CSS)
    execSync(
      `"${chrome}" --headless --disable-gpu --no-sandbox ` +
        `--print-to-pdf="${pdfFile}" --no-pdf-header-footer ` +
        `"file://${htmlFile}"`,
      { timeout: 60_000, stdio: "pipe" },
    );

    if (!fs.existsSync(pdfFile))
      throw new Error("PDF was not generated by Chrome.");

    const printer = resolvePrinter();
    if (!printer)
      throw new Error(
        "No printer found.\n" +
          "  → Add your printer in System Settings → Printers & Scanners\n" +
          '  → Or run:  PRINTER_NAME="YourPrinter" npm run print-service',
      );

    execSync(`lp -d "${printer}" "${pdfFile}"`, { timeout: 10_000 });
    console.log(
      `[${new Date().toLocaleTimeString()}] ✓ Printed to: ${printer}`,
    );
  } finally {
    try {
      fs.unlinkSync(htmlFile);
    } catch {}
    try {
      fs.unlinkSync(pdfFile);
    } catch {}
  }
}

const server = http.createServer((req, res) => {
  res.setHeader("Access-Control-Allow-Origin", "*");
  res.setHeader("Access-Control-Allow-Methods", "POST, OPTIONS");
  res.setHeader("Access-Control-Allow-Headers", "Content-Type");

  if (req.method === "OPTIONS") {
    res.writeHead(200);
    res.end();
    return;
  }

  if (req.method === "GET" && req.url === "/") {
    const printer = resolvePrinter();
    res.writeHead(200, { "Content-Type": "text/plain" });
    res.end(
      `R99 Print Service OK\nPrinter: ${printer ?? "none — see startup log"}`,
    );
    return;
  }

  if (req.method === "POST" && req.url === "/print") {
    let body = "";
    req.on("data", (chunk) => (body += chunk.toString()));
    req.on("end", () => {
      try {
        printHtml(body);
        res.writeHead(200, { "Content-Type": "application/json" });
        res.end('{"ok":true}');
      } catch (e) {
        console.error("✗ Print error:", e.message);
        res.writeHead(500, { "Content-Type": "application/json" });
        res.end(JSON.stringify({ ok: false, error: e.message }));
      }
    });
    return;
  }

  res.writeHead(404);
  res.end();
});

server.listen(PORT, "127.0.0.1", () => {
  const chrome = findChrome();
  const printer = resolvePrinter();
  const printers = listPrinters();
  console.log("━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━");
  console.log(" R99 Print Service");
  console.log(`  URL:      http://localhost:${PORT}/print`);
  console.log(`  Chrome:   ${chrome ?? "⚠  NOT FOUND"}`);
  console.log(
    `  Printer:  ${printer ?? "⚠  NONE — add printer in System Settings"}`,
  );
  if (printers.length > 0) {
    console.log(`  Available printers:`);
    printers.forEach((p) => console.log(`    - ${p}`));
  } else {
    console.log("  ⚠  No printers found (lpstat -a returned empty)");
  }
  console.log("━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━");
  if (PRINTER_NAME)
    console.log(`  Using PRINTER_NAME override: ${PRINTER_NAME}`);
});
